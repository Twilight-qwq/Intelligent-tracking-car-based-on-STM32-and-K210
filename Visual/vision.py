# -*- coding: utf-8 -*-
"""
============================================================
 vision.py  ·  相机几何 + 找线
------------------------------------------------------------
 【这个文件在整个系统里干什么】

 摄像头拍到的是 160×120 的灰度图（一张黑白照片）。
 程序要从这张照片里回答一个问题：
     "车现在偏了多少？"

 答案用"像素"表示：车道中心线在画面第几列，
 和画面正中间（第 80 列）差多少个像素。
 这个数就是后面 judge.py 和 STM32 用来说"往左打还是往右打"的依据。

 ------------------------------------------------------------
 【为什么要有"相机几何"这一节】

 摄像头装多高、低头多少度、视场角多大——这三个数决定了
 "画面上的第几行，对应车前面多少米"。

 如果不知道这个换算，就只能靠人肉一个个试"扫哪几行"，
 换个安装高度就得重试一遍。有了几何计算，程序上电自己算：
     高度 20cm、低头 30° → 第 71 行是车前 0.26m，第 34 行是车前 0.94m
 改 config.py 里的三个数，扫描行会自己跟着变。

 ------------------------------------------------------------
 【为什么叫"扫 5 行"而不是"整张图都算"】

 一张图有 120 行，全算太慢，而且大部分行是没用的（天空、远处糊成一团）。
 赛道在同一时刻是"直"的，只在 5 个不同距离上取样，
 就足够推算出车偏了多少、前面弯有多大。

 ------------------------------------------------------------
 对外只有两个函数：
     find_lane(img)   扫完整个画面，返回一堆数字
     print_table()    启动时把算出来的表打出来看看
============================================================
"""

import math
import config as C

IMG_W, IMG_H = 160, 120          # 画面宽高，要和 main.py 里的 QQVGA 一致
CENTER_X = IMG_W // 2            # 画面正中间的列号 = 80


# ============================================================
#  一、由"装多高、低多少头、视场多大"推出扫描行
# ============================================================

# ---- 针孔相机模型：把"角度"换算成"像素" ----
# 想象光线从镜头中心射出去，落在感光元件上形成一个点。
# 同一个物体，离得越远，成像越靠近画面中心——这就是"近大远小"。
# 描述这个比例的常数就是焦距 F0。
#
# F0 的算法：画面半宽 80 像素对应半个视场角（90°÷2 = 45°），
# 直角三角形里 tan(半视场角) = 半宽 ÷ 焦距，反过来就求出焦距。
F0 = (IMG_W / 2.0) / math.tan(math.radians(C.HFOV_DEG) / 2.0)   # 焦距（像素）

# ---- 把安装角度先算好 ----
# _S / _C 是低头角的正弦和余弦，后面每算一行都要用，先算一次省事。
# _H 是镜头离地高度，从厘米换算成米，因为后面所有距离都用米，单位要统一。
_S = math.sin(math.radians(C.CAM_PITCH_DEG))
_C = math.cos(math.radians(C.CAM_PITCH_DEG))
_H = C.CAM_H_CM / 100.0


def row_slant(v):
    """第 v 行对应的斜距（米）。地平线以上返回 0。

    什么是"斜距"？
      从镜头中心沿着这条光线一直射出去，打到地面那个点，
      镜头到那个点的直线距离（斜着量），就是斜距。
      它不是"车前面多少米"，是"光线走了多远"。
      后面算横向像素间距要用到它，所以先单独算出来。

    v 是行号：0 在最上面（最远），119 在最下面（最近）。
    """
    # dy：这一行相对画面中心偏了多少，换算成"正切值"（没有单位）。
    # 画面正中间那一行 dy = 0；往上（行号变小）就是抬头看。
    dy = (v - IMG_H / 2.0) / F0

    # wz：这条光线在"朝下"方向上的分量。
    # 减 _S 是因为镜头本来就低着头，即使画面中心那条光线也是朝下走的。
    wz = -_C * dy - _S

    # wz >= 0 说明这条光线朝上或水平 —— 射到天上去了，永远打不到地面。
    # 返回 0 表示"这一行没有地面"，调用它的函数会自己去处理这种情况。
    if wz > -1e-6:
        return 0.0

    # 相似三角形：高度 ÷ 朝下的比例 = 光线长度
    return -_H / wz


def row_dist(v):
    """第 v 行正中央对应的车前水平距离（米）。

    和 row_slant 的区别：
      斜距   = 光线本身有多长（斜着量）
      水平距离 = 把这条光线投影到地面上，车往前走了多远
    我们真正关心"车前面多少米"，所以用这个。

    注意：这个距离只对"画面正中间那一列"成立。
    画面左右两边的像素其实再远一点（斜着看更远），
    但对"挑扫描行"来说这点误差无所谓。
    """
    t = row_slant(v)
    if t <= 1e-6:
        return 0.0
    dy = (v - IMG_H / 2.0) / F0
    # (-_S*dy + _C)：把斜距投影到地面上的比例
    return (-_S * dy + _C) * t


def row_gap_of(v):
    """第 v 行：外侧黑线中心 -> 车道中心，差多少像素。

    【这个数是干什么用的？】
    赛道有两条黑线（内圈一条、外侧一条），车道中心在两条线正中间。
    理想情况两条都看得见，取中点就行。

    但过弯时内圈那条线会先拐走，画面里只剩外侧一条。
    这时不能瞎猜，得知道"外侧线到车道中心隔多远"——在画面里隔多少像素。
    知道这个数，量到外侧线就能反推出车道中心。

    【为什么每一行都不一样？】
    因为"近大远小"。同样是 25cm 的半车道宽，
    在近处的行（画面底部）可能占 60 个像素，
    在远处的行（靠近地平线）只占 20 个像素。
    所以每一行都要单独算。

    公式 pixels = F0 × (实际长度 ÷ 距离) 是针孔相机的标准投影公式。
    0.25 就是半车道宽 0.25 米（赛道宽 50cm，一半 25cm）。
    以后换更宽的赛道，只改这一个数。
    """
    t = row_slant(v)
    if t <= 1e-6:
        return 0
    return int(F0 * 0.25 / t + 0.5)


def pick_rows():
    """在"两根线都塞得进画面"的行里，平均挑 N_SCAN 行。

    【为什么不把所有行都扫？】
    一行 152 个像素，120 行就是一万八千多次读像素。
    K210 虽然不慢，但每秒要跑 25~30 帧，能省就省。
    更重要的原因是远处的行根本没法用：
        太远：两条线糊成一小团，分不清是线还是噪点
        太近：车道已经撑出画面，只看得见一条线
    所以只在"间距落在 GAP_MIN ~ GAP_MAX 之间"的行里挑。

    【怎么挑？】
    先收集所有合格的行号，再在这一段里等间隔取 N_SCAN 个。
    等间隔是为了让近处远处都有样本，不会只盯着脚底下看。

    最后 reverse() 把顺序改成"由近到远"，
    因为后面算加权平均时近处的行权重更大，近的排前面更直观。
    """
    ok = []
    for v in range(IMG_H):
        g = row_gap_of(v)
        if C.GAP_MIN <= g <= C.GAP_MAX:
            ok.append(v)
    if len(ok) < C.N_SCAN:
        ok = list(range(12, 60))            # 兜底，说明参数填得离谱

    # 在 ok 这一段里等间隔取 N_SCAN 个位置
    out = []
    n = len(ok) - 1
    for i in range(C.N_SCAN):
        v = ok[int(i * n / (C.N_SCAN - 1.0) + 0.5)] + C.ROW_TWEAK
        # 防止算出来的行号跑出画面（行号只能是 0 ~ 119）
        if v < 0:
            v = 0
        elif v > IMG_H - 1:
            v = IMG_H - 1
        out.append(v)
    out.reverse()                           # 改成 近 -> 远
    return out


# 上电时（import 这一下）立刻算一次，之后整个程序都用这份表。
SCAN_ROWS = pick_rows()                     # 5 个行号，近的在前
ROW_GAP = [row_gap_of(v) for v in SCAN_ROWS]   # 对应的像素间距，运行时会被修正

# 权重：近处的行看得更清、算出来的偏差更可信，给 3 分；
# 远处的行容易受干扰，只给 1 分。加权平均时按这个比例算。
SCAN_WEIGHT = (3, 3, 2, 2, 1)


def horizon_row():
    """地平线在第几行。这行以上是天空，不用扫。

    为什么需要它？
    画面顶部那几行拍的是远处地面和天空，对找黑线没用。
    知道地平线在哪，调试时一眼就能看出"扫描行是不是选到天上去了"
    （print_table 会把它打印出来）。
    """
    for v in range(IMG_H):
        # row_slant(v) 大于 0 = 这条光线朝上、打不到地面 = 地平线以上
        if row_slant(v) > 0:
            return v
    return IMG_H - 1


def print_table():
    """启动时把算出来的表打印出来，用来检查参数填得对不对。

    这是整个文件里最"救命"的函数：
    如果 CAM_H_CM / CAM_PITCH_DEG 填错了，算出来的距离会和实际差很远。
    一眼就能看出来。**上车前一定要看一遍这张表。**
    """
    hz = horizon_row()
    print("焦距 F=%.1f px   地平线在第 %d 行   最近能看 %.2f m"
          % (F0, hz, row_dist(IMG_H - 1)))
    for i in range(C.N_SCAN):
        print("  行 %3d  车前 %4.2f m  间距 %3d px  权重 %d"
              % (SCAN_ROWS[i], row_dist(SCAN_ROWS[i]), ROW_GAP[i], SCAN_WEIGHT[i]))


# ============================================================
#  二、扫一行
# ============================================================

def scan_row(img, y, gi):
    """扫描第 y 行。返回 (车道中心 x, 黑点数, 单线标记)。

    单线标记：0 = 两根都在   1 = 只剩外侧那根   2 = 只剩内圈那根
              -1 = 一根都没有
    车道中心找不到时 x = -1。

    gi 是这个行在 SCAN_ROWS 里的序号（0~4），用来取对应的理论间距。

    【整行处理分 3 步】
      1. 把这一行的像素全读出来
      2. 自己算一个黑白分界线
      3. 找出连续的黑色段，判断哪些才是"线"
    """
    # ---- 1. 读一整行 ----
    # gp / add 是为了提速：Python 里每写一次 img.get_pixel 都要先查一次属性，
    # 循环里重复上千次很浪费。提前取出来存成局部变量，能快不少。
    gp = img.get_pixel
    vals = []
    add = vals.append
    x = C.X_MIN
    while x <= C.X_MAX:
        add(gp(x, y))
        x += 1

    # ---- 2. 这一行自己的黑白分界线（所以不怕灯光变）----
    # 【为什么要"这一行自己算"？】
    # 如果全场用同一个阈值，灯光一边亮一边暗、或者自动曝光慢慢变化，
    # 就会一块判对一块判错。
    # 每一行单独找"这一行最暗"和"这一行最亮"，按比例取中间值，
    # 相当于每一行都在自己适应亮度。这叫"自适应阈值"。
    lo = min(vals)
    hi = max(vals)
    # 最亮和最暗差不多，说明这一行根本没看到黑线（可能全是白地），
    # 直接判定这一行没有线，不浪费时间继续算。
    if hi - lo < C.CONTRAST_MIN:
        return -1, 0, -1
    thr = lo + int((hi - lo) * C.BLACK_RATIO)

    # ---- 3. 找黑段 ----
    # 【什么叫"黑段"？】
    # 一行像素从左到右，连续好几个都低于阈值，这一串就叫一个黑段。
    # 黑段的长度代表"这条黑线在画面里有多宽"。
    n = len(vals)
    first = -1      # 第一个合格黑段的中心列
    last = -1       # 最后一个合格黑段的中心列
    cnt = 0         # 合格黑段的个数
    dark = 0        # 这一行一共多少黑色像素（判断横线要用）
    i = 0
    while i < n:
        if vals[i] < thr:
            # 从 i 一直往右数，数到不变黑为止，j 就是黑段结束的位置
            j = i
            while j < n and vals[j] < thr:
                j += 1
            dark += j - i

            # 【为什么要限制黑段长度？】
            # 太短（< RUN_MIN）：大概率是地面污点、反光的噪点，不是线
            # 太长（> RUN_MAX）：要么两根线糊成一片，要么是横线/大片阴影
            # 只有长度合适的才算"一条线"。
            if C.RUN_MIN <= (j - i) <= C.RUN_MAX:
                c = (i + j - 1) // 2 + C.X_MIN   # 黑段中心，换算回真实列号
                if cnt == 0:
                    first = c
                last = c
                cnt += 1

            i = j       # 跳过这一整段，接着找下一段
        else:
            i += 1

    if cnt == 0:
        return -1, dark, -1

    gap = ROW_GAP[gi]

    # ---- 两根都在，间距对得上：最可靠 ----
    # 最理想的情况：一条线在左、一条在右，中点就是车道中心。
    # 但还要检查"两线间距"是不是和理论值差不多——
    # 差太多说明看到的可能不是赛道两条边（比如旁边的门框、桌腿）。
    if cnt >= 2:
        half = (last - first) // 2
        d = half - gap
        if d < 0:
            d = -d
        if d <= C.GAP_TOL:
            # 【自适应修正】
            # 实测间距 half 和理论 gap 差一点，就把理论值往实测方向挪 1/16。
            # 这样就算 config 里的高度量错了 2cm，跑一会儿也会自己纠回来。
            # (gap*15 + half) >> 4 就是 (15*gap + half) ÷ 16，用移位比除法快。
            ROW_GAP[gi] = (gap * 15 + half) >> 4   # 自适应修正间距表
            return (first + last) // 2, dark, 0

    # ---- 只剩一根：判断它是外侧还是内圈 ----
    # 【为什么要判断？】
    # 顺时针跑的时候，外侧线永远在车左边、永远连续；
    # 内圈线在过弯前半米左右就会先拐出画面。
    # 所以"只剩左边那根"和"只剩右边那根"含义完全不一样。
    #
    # 判断方法：这根线明显偏左（比画面中心还左边 SIDE_DEAD 像素），
    # 那它就是外侧线，车道中心应该在它右边 gap 像素处。
    if first < CENTER_X - C.SIDE_DEAD:
        return first + gap, dark, 1
    if last > CENTER_X + C.SIDE_DEAD:
        return last - gap, dark, 2
    # 只剩一根又几乎在正中间 —— 分不清是外侧还是内圈。
    # 猜错方向就是反的，宁可不给结果（返回 -1 让上层忽略这一行）。
    return -1, dark, -1


# ============================================================
#  三、扫全部行，合成一个结果
# ============================================================

def find_lane(img):
    """返回 (误差, 远处误差, 有效行数, 横线条数, 远处有效行数, 右弯信号)。

    这是 vision.py 的主函数，每帧调用一次。

    【6 个返回值分别是】
      err       : 5 行加权平均后的偏差（像素），车偏左为正
      far       : 只看最远两行的偏差，用来判断"前面弯有多大"
      hits      : 有几行成功找到了车道中心（0 = 完全丢线）
      bars      : 有几行整行都是黑的（可能是终点横线）
      far_hits  : 最远两行里成功找到几行（0 = 前面看不见了）
      corner    : 1 = 判断前面是右弯，0 = 不是

    【为什么用加权平均，不用简单平均？】
    近处的行像素多、算得准；远处的行一个像素就代表好几厘米，容易抖。
    给近处 3 分、远处 1 分，算出来的偏差更稳定。
    """
    n = len(SCAN_ROWS)
    sum_w = 0       # 权重总和
    sum_e = 0       # 偏差 × 权重 的累加
    far_w = 0       # 远端的权重总和
    far_e = 0       # 远端的偏差 × 权重 的累加
    hits = 0        # 找到车道中心的行数
    far_hits = 0    # 远端找到的行数
    bars = 0        # 疑似横线的行数
    corner = 0      # 右弯信号
    span = C.X_MAX - C.X_MIN + 1    # 一行有效像素的个数

    for i in range(n):
        y = SCAN_ROWS[i]
        mid, dark, only = scan_row(img, y, i)

        # 整行八成都是黑的 —— 这不是线，是横线（终点线、或者大片阴影）
        if dark * 10 >= span * 8:               # 这一行 80% 都是黑的 = 横线
            bars += 1

        # 【右弯判断】
        # 最近两行（i = 0,1）只剩外侧那根线，而且按外侧线推出来的
        # 车道中心还在画面很靠左的位置（< CORNER_X）——
        # 说明内圈线已经拐到右边去了，前面是个右弯。
        if only == 1 and i <= 1:
            if 0 <= mid - ROW_GAP[i] < C.CORNER_X:
                corner = 1

        if mid < 0:
            continue        # 这一行没找到线，跳过，不参与平均

        # 偏差 = 车道中心 − 画面中心。
        # 正数表示车道在画面右边 = 车偏左了 = 要往右打。
        e = mid - CENTER_X
        w = SCAN_WEIGHT[i]
        sum_w += w
        sum_e += w * e
        hits += 1

        if i >= n - 2:                          # 最后两行 = 最远的两行
            far_w += w
            far_e += w * e
            far_hits += 1

        if C.DEBUG_DRAW:
            # 在画面上把找到的车道中心点画出来，IDE 预览里直接能看见。
            # 调试就看这个：点应该正好落在两条黑线中间。
            img.draw_circle(mid, y, 2, color=0, fill=True)

    if sum_w == 0:
        # 一行都没找到，返回全 0 / 0 命中，让上层走"丢线"逻辑
        return 0, 0, 0, bars, 0, corner

    # 加权平均：总加权偏差 ÷ 总权重。
    # 用 // 整除而不是 / 浮点除法，因为后面要转成整数发给串口，
    # 而且 K210 上整数运算比浮点快。
    err = sum_e // sum_w
    # 远端一行都没找到时，用整体误差顶替，
    # 避免上层拿到 0 误判成"车正对着车道"。
    far = far_e // far_w if far_w > 0 else err
    return err, far, hits, bars, far_hits, corner
