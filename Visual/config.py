# -*- coding: utf-8 -*-
"""
============================================================
 config.py  ·  所有可以调的东西都在这一个文件里
------------------------------------------------------------
 这个文件里没有任何逻辑，全是数字和开关。调参只改这里。

 【为什么单独搞一个配置文件？】
 因为调参时要反复改数字、反复存到板子上。
 如果这些数字散落在 vision.py、judge.py 里，改一次得翻三个文件，
 很容易改漏、改错。集中在这一个文件，改完只存这一个就行。

 【改完必须做的事】
 这些数字是"上电时"读进去的（vision.py 一 import 就开始算），
 所以改完要把 config.py 重新保存到板子上，再运行 main.py 才生效。
============================================================
"""

# ------------------------------------------------------------
# 一、摄像头怎么装的（上车前必须量准）
# ------------------------------------------------------------
# 【这三个数决定"画面第几行 = 车前多少米"】
# vision.py 上电时会拿它们算出：该扫哪 5 行、每行两条黑线隔多少像素。
# 填错了不会报错，但扫描行可能选到不合适的位置（比如全选到天上），
# 表现出来就是"明明线在眼前，程序却说没看见"。
#
# 怎么量：
#   CAM_H_CM      ：卷尺从镜头中心垂直量到地面，单位厘米
#   CAM_PITCH_DEG ：镜头光轴和水平面的夹角，低头为正
#   HFOV_DEG      ：镜头水平视场角，看摄像头参数表
# 量不准也没关系，看 vision.py 启动时打印的那张表可以反推。
CAM_H_CM = 20.0             # 镜头离地高度，单位厘米
CAM_PITCH_DEG = 30.0        # 镜头往下低头多少度
HFOV_DEG = 90.0             # 镜头水平视场角

# 应急旋钮：把选出来的扫描行整体上下平移几行。
# 发现行选得太高（看太远、看不清）就填 +5，太低就填 -5。正常填 0。
ROW_TWEAK = 0               # 整组扫描行上/下平移几行（应急微调）

# 扫几行。行数越多越稳（抗干扰），但也越慢。5 行是经验值。
N_SCAN = 5                  # 用几行扫描

# 【筛选扫描行的条件】
# 每一行都会算出一个"外侧线到车道中心"的像素数（叫 gap）。
# gap 必须落在这个范围里，这一行才会被选中：
#   gap < GAP_MIN：这一行太远，两条线挤成一团，分不清是线还是噪点
#   gap > GAP_MAX：这一行太近，车道已经撑出画面，只看得见一条线
GAP_MIN = 22                # 最远那行：黑线至少要占这么多像素
GAP_MAX = 62                # 最近那行：再近车道就撑出画面了


# ------------------------------------------------------------
# 二、找线
# ------------------------------------------------------------
# 【RUN_MIN / RUN_MAX：合格黑段的长度范围】
# 一行像素里连续几个点都发黑，就叫一个"黑段"。
#   太短 = 地面污点、反光噪点，不是线
#   太长 = 两根线糊成一片，或者是横线/阴影
# 只有长度落在这个区间里的黑段，才被当成"一条线"。
RUN_MIN = 3                 # 连续几个黑点才算一条线（滤噪点）
RUN_MAX = 26                # 超过这么宽就不是"线"，是糊成一片

# 【GAP_TOL：间距容差】
# 两线间距和理论值的差在多少像素以内，还认为"看到的就是赛道"。
# 设太小：老是判不合格，白丢数据。设太大：旁边的桌子腿也会被当成线。
GAP_TOL = 14                # 实测间距和理论值差多少还算数

# 【SIDE_DEAD：单线时的"不敢判断区"】
# 只剩一根线时要判断它是外侧还是内圈，靠的是"它偏左还是偏右"。
# 如果这根线离画面中心太近（小于 SIDE_DEAD 像素），就分不清了，
# 宁可这一行不用，也不要猜错——猜错方向是反的，比没有更糟。
SIDE_DEAD = 12              # 只剩一根线时，它离画面中心多近就不敢判左右

# 【每个像素"黑不黑"怎么定？】
# 这一行最暗的值 + (最亮 - 最暗) × BLACK_RATIO，就是分界线。
# 每行各算各的，所以灯光一边亮一边暗也不怕（这叫自适应阈值）。
#   CONTRAST_MIN：最亮和最暗差不到这么多，说明这一行根本没黑线，直接放弃
#   BLACK_RATIO ：分界线取在"最暗和最亮之间"的什么位置
CONTRAST_MIN = 70           # 这一行最亮减最暗至少多少才认
BLACK_RATIO = 0.40          # 阈值 = 最暗 + (最亮 - 最暗) * 0.40

# 每行从左扫到右的范围。两边留几个像素不扫，
# 因为画面边缘容易有暗角，扫描进去反而会干扰"最亮/最暗"的判断。
X_MIN = 4                   # 每行从左扫到哪
X_MAX = 155                 # 每行扫到右到哪


# ------------------------------------------------------------
# 三、判断
# ------------------------------------------------------------
# 【CALIB_OFFSET：对正中用】
# 车摆正放在车道中间时，程序读出来的 err 应该尽量接近 0。
# 如果读出来是 7，就把 7 填到这里，以后这个 7 会被自动减掉。
CALIB_OFFSET = 0            # 车摆正时读出多少就填多少
ERROR_GAIN = 1.0            # 误差再放大或缩小，一般不用改

# 【CURV_T1 / CURV_T2：用"远处偏差"决定降速档位】
# 远处偏得越多，说明前面弯越急，基础速度要降得越低。
#   远处偏差 < CURV_T1 ：直道，全速
#   在 T1 和 T2 之间    ：一般弯，中速
#   > CURV_T2           ：急弯，慢速
# 只影响"什么时候减速"，不影响打方向。
CURV_T1 = 10                # 远处偏差 > 10 像素 -> 状态 1
CURV_T2 = 22                # 远处偏差 > 22 像素 -> 状态 2

# 【提前打方向（右弯专用）】
# 摄像头装 20cm 高、低头 30°，离车 0.25m 以内的路面根本看不见。
# 所以每到弯口最后二三十厘米，画面里只剩外侧一根线。
# 这时按"外侧线还在、但内圈线没了"判定前面是右弯，抢先打方向。
#   CORNER_BIAS   ：确认是右弯后，把误差直接顶到这个数（负数是左弯）
#   CORNER_TRIGGER：只有当前误差还小于这个数，才算"刚进弯"，避免重复触发
#   CORNER_X      ：按外侧线推出来的车道中心在这个列号左边 = 前面是右弯
# 前提：这条赛道是顺时针跑、三个弯全是右弯。换赛道要改这里。
CORNER_BIAS = 40            # 确认前面是右弯时，把误差顶到多少
CORNER_TRIGGER = 8          # 但只有当前误差还小于这个数才算"刚进弯"
CORNER_X = 50               # 外侧线在这个位置左边 = 前面是右弯

# 【平滑：让误差别抖】
#     err = 旧值 + (新值 - 旧值) ÷ 2^SMOOTH_SHIFT
# 0 = 不滤波（反应最快，但抖）；1 = 挪一半；2 = 挪四分之一（更平滑但更迟钝）
SMOOTH_SHIFT = 0            # 0 = 不滤波；画面抖就改 1 或 2

# 【丢线怎么扛】
# 丢线是常态（过弯、反光、压线），不能一丢就停。
#   LOST_KEEP    ：丢线不超过这么多帧，就照上一帧的结果继续发
#   LOST_ERR_HOLD：超过之后，1 = 沿用上次误差继续开，0 = 误差归零
# 注意：丢线时状态最多降到 1，永远不会发 3（3 代表到达终点）。
LOST_KEEP = 10              # 丢线 10 帧以内：照上次的结果继续发
LOST_ERR_HOLD = 1           # 超过 10 帧：1=沿用上次误差，0=发 0

# 【终点线检测】默认关。现在只认"整行都变黑"这一种特征。
# 要开得先说清楚终点线长什么样，否则容易把阴影误判成终点。
FINISH_ENABLE = False       # 终点线检测，默认关
FINISH_ROWS = 4             # 几行整行变黑才算横线
FINISH_FRAMES = 3           # 连续几帧才认


# ------------------------------------------------------------
# 四、串口
# ------------------------------------------------------------
# 波特率、引脚必须和 STM32 那边对得上，改一边就要改另一边。
BAUD = 115200               # 必须和 STM32 一致
PIN_TX = 24                 # K210 IO24 -> STM32 PA10
PIN_RX = 25                 # 用不到，但 fpioa 要先占住


# ------------------------------------------------------------
# 五、调试
# ------------------------------------------------------------
#   VFLIP / HMIRROR：摄像头装反了用这两个翻回来。
#     注意 HMIRROR 打开时 judge.py 会自动把误差取反，所以方向不会反。
#   DEBUG_DRAW：在 IDE 预览的画面上画点、画十字，看程序到底认到了哪。
#   PRINT_EVERY：每多少帧打印一行状态，调参全靠它。
#   PRINT_TABLE：启动时打印扫描行表，检查高度/角度填得对不对。
VFLIP = False               # 画面上下颠倒改 True
HMIRROR = False             # 画面左右镜像改 True（误差自动取反）
DEBUG_DRAW = True           # 画面上画标记
PRINT_EVERY = 30            # 每 30 帧打印一行
PRINT_TABLE = True          # 启动时把算出来的表打出来
