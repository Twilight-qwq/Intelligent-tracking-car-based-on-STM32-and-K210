# ---------- 一、摄像头安装（上车前量准） ----------
CAM_H_CM = 20.0             # 镜头离地高度，厘米
CAM_PITCH_DEG = 30.0        # 镜头低头角度，度
HFOV_DEG = 90.0             # 镜头水平视场角，度

ROW_TWEAK = 0               # 整组扫描行上下平移（应急微调，正常 0）
N_SCAN = 5                  # 扫几行

# 合格扫描行的半间距范围（外侧线到车道中心的像素数）
GAP_MIN = 22                # 小于它 = 太远，两线挤成一团
GAP_MAX = 62                # 大于它 = 太近，车道撑出画面

# ---------- 二、找线 ----------
RUN_MIN = 3                 # 黑段最短几像素才算线（滤噪点）
RUN_MAX = 26                # 黑段最宽几像素（再宽就是糊成一片）

GAP_TOL = 14                # 实测间距和理论值差多少以内还算数
SIDE_DEAD = 12              # 单线时离画面中心多近就分不清内外线

CONTRAST_MIN = 70           # 本行最亮减最暗至少多少才认（否则没线）
BLACK_RATIO = 0.40          # 阈值 = 最暗 + (最亮-最暗)*0.40

X_MIN = 4                   # 每行从左扫到第几列（避开暗角）
X_MAX = 155                 # 每行扫到第几列

# ---------- 三、判断 ----------
CALIB_OFFSET = 0            # 车摆正时读出多少偏差就填多少
ERROR_GAIN = 1.0            # 误差整体放大/缩小

CURV_T1 = 10                # 远处偏差 > 10 像素 -> 状态 1（中速）
CURV_T2 = 22                # 远处偏差 > 22 像素 -> 状态 2（慢速）

CORNER_BIAS = 40            # 确认右弯时把误差直接顶到这个数
CORNER_TRIGGER = 8          # 只有当前误差小于它才算"刚进弯"
CORNER_X = 50               # 外侧线推出的中心在这个列号左边 = 右弯

SMOOTH_SHIFT = 0            # 指数平滑：0=不滤波，1/2=越来越平滑但迟钝

LOST_KEEP = 10              # 丢线这么多帧以内照上次结果继续发
LOST_ERR_HOLD = 1           # 超过之后 1=沿用上次误差，0=发 0

FINISH_ENABLE = False       # 终点线检测，默认关
FINISH_ROWS = 4             # 几行整行变黑才算横线
FINISH_FRAMES = 3           # 连续几帧才认

# ---------- 四、串口 ----------
BAUD = 115200               # 必须和 STM32 一致
PIN_TX = 24                 # K210 IO24 -> STM32
PIN_RX = 25                 # 用不到，但要先占住

# ---------- 五、调试 ----------
VFLIP = False               # 画面上下颠倒改 True
HMIRROR = False             # 画面左右镜像改 True（误差自动取反）
DEBUG_DRAW = True           # 在预览画面上画标记
PRINT_EVERY = 30            # 每多少帧打印一行
PRINT_TABLE = True          # 启动时打印扫描行表
