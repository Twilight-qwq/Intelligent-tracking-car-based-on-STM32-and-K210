/* ============================================================================
 * main.c —— 主循环，外加整个工程的思路
 *
 * 三层分工：
 *   BSP 层（bsp_*.c）        硬件的读写：GPIO / 定时器 / 串口 / 编码器 / 陀螺仪
 *   MID 层（mid_*.c）        纯算法：协议解析、PID
 *   APP 层（app_control.c）  「车该怎么跑」—— 所有策略都在那一个文件里
 *
 * 主循环按四个节拍调 app_control.c，节拍判断在每个函数第一行：
 *   5ms    读编码器 → 读陀螺仪 → 累计里程 → 弯道状态机 → 速度环出 PWM
 *   10ms   读按键
 *   30ms   取一帧视觉 → 算左右轮目标速度（外环方向环）
 *   100ms  启停 / 蓝牙 / 遥测 / 指示灯
 *
 * 车靠三个东西知道「自己在哪、该转多少」：
 *   视觉（K210）   近 4 行算偏差（27.5 / 34.6 / 45.0 / 63.9 厘米）→ 直道修方向
 *   编码器里程     段内里程 Corner_SegMileage → 判断「现在该不该转」
 *   陀螺仪         累计角度 → 判断「转够了没有」
 *
 * 详细的「为什么这么写、踩过什么坑、数字怎么来的」见 Doc/代码说明.md，
 * 源码里只留一行摘要 + 小节号。
 * ========================================================================== */

#include "app_control.h"
int main(void)
{
	App_Init();
	while(1)
	{
		AppTask_Idle();
		uint32_t timestamp = App_Clock();
		AppTask_5ms(timestamp);
		AppTask_10ms(timestamp);
		AppTask_30ms(timestamp);
		AppTask_100ms(timestamp);
	}
}
