#ifndef __GYRO_H
#define __GYRO_H
#include "stm32f10x.h"

/* =========================================================================
 * 陀螺仪 ICM-20602（软件 I2C，SCL = PB0，SDA = PB1）      2026-11-21 新增
 *
 * 干什么：量"车真的转了多少度"，替代"数编码器计数"的做法。
 *         编码器数的是轮子转了多少，中间隔着打滑；陀螺仪直接量车身转速。
 *
 * 为什么用软件 I2C 而不是硬件 I2C：
 *   STM32F103 的硬件 I2C 在从机拉住总线时可能卡死，而这里是 5 毫秒控制周期，
 *   卡死 = 电机失控。软件 I2C 每一位都是固定时钟数，最坏是"这次读失败"，
 *   不会把主循环挂住。
 *
 * 为什么不需要卡尔曼滤波 / 姿态解算：
 *   那些是为了"长时间知道车头朝哪"。这里只积分 0.4 秒（转一个弯的时间），
 *   零偏校准后 0.1°/秒，0.4 秒只漂 0.04°，远小于 5° 的容差。
 *   每过一个弯就把角度清零，不累积。
 *
 * 实测（2026-11-21）：Z 轴读数在转车时冲得最大 → 模块平放，Z 是竖直轴。
 *   手转 90°：顺时针 = −90，逆时针 = +90。
 *
 * 量程 ±500 度/秒（1 度/秒 = 65.5 个数字）：上车转 90° 平均 240 度/秒，
 *   ±250 只剩 4% 余量会削顶，所以换成 ±500。
 * 死区 1 度/秒：小于 1 度/秒当作没转，压掉零偏残余造成的慢漂
 *   （实测过 21 秒漂 10 度的现象）。
 * ========================================================================= */

void Gyro_Init(void);
/* 功能：确认芯片活着、唤醒、配置量程
 * 参数：无
 * 返回：无
 * 说明：芯片不在时 Gyro_IsAvailable 保持 0，后面所有函数自动跳过，不影响跑车
 */

void Gyro_Update(void);
/* 功能：读一次三轴数据；前 1 秒测零偏，之后按 Z 轴积分出角度
 * 参数：无
 * 返回：无
 * 说明：按控制周期调用（5 毫秒一次），一个周期只调一次！！
 */

uint8_t Gyro_IsOk(void);
/* 功能：芯片到底认到没有
 * 参数：无
 * 返回：1 = 芯片活着；0 = 不在（此时角度恒为 0，上层必须退回编码器方案）
 * 说明：函数名里的 Ok 就是"可用"，返回 0 时其余读角度的接口全部返回 0
 */

uint8_t Gyro_GetWhoAmIValue(void);
/* 功能：读回来的身份号
 * 参数：无
 * 返回：ICM-20602 = 18(0x12)；MPU6050 = 104(0x68)；0 或 255 = 没接上
 * 示例：台架模式下正常显示 18
 */

int16_t Gyro_GetAxisXRaw(void);
int16_t Gyro_GetAxisYRaw(void);
int16_t Gyro_GetAxisZRaw(void);
/* 功能：三轴原始读数（台架诊断用）
 * 参数：无
 * 返回：原始数字，不是度。静止时在一个固定值（零偏）附近小幅抖
 * 说明：竖直轴是哪一根，手转一下看哪个数冲得最大就知道了
 */

float Gyro_GetZeroBias(void);
/* 功能：零偏（上电后：先等 50 毫秒、再丢掉 200 毫秒的样本，然后采 1 秒求平均）
 * 参数：无
 * 返回：Z 轴静止时的原始读数平均值
 * 示例：±500 度/秒档下约 80，除以 65.5 就是 1.22 度/秒，很小
 */

float Gyro_GetTotalAngle(void);
/* 功能：累计角度
 * 参数：无
 * 返回：从 Gyro_ResetTotalAngle() 到现在的转角，单位：度
 * 说明：逆时针（俯视）为正，顺时针为负
 * 示例：顺时针转 90° 返回 −90
 */

void Gyro_ResetTotalAngle(void);
/* 功能：把累计角度清零
 * 参数：无
 * 返回：无
 * 说明：每个弯开始转弯的那一刻调用，这样角度不跨弯累积
 */

uint16_t Gyro_GetReadErrorCount(void);
/* 功能：读失败次数
 * 参数：无
 * 返回：累计读失败的次数，应该一直是 0；在涨说明接线松了
 */
#endif
